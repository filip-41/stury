#!/usr/bin/env python3
"""Write core/spell/entities.odin and the core/spell/entities/*.bin it loads: the trie of the HTML standard's named
character references, read from core/spell/entities/entities.json, the standard's own file, vendored with the digest
below. HTML's tokenizer reads it, and XML for a document whose public identifier the HTML standard lists.

Each node is one character of a name. NODES holds `ch | count << 7 | first << 13`: the node's character, how many
children it has and the index of the first, the children of a node stored in a row in byte order. Node 0 is the root.
TERMINALS[i] is 0 for a node no name ends at, else 1 + the index of its value: the value's UTF-8 bytes are
TEXT[OFFSETS[v]:OFFSETS[v + 1]].

Run from the repository root:
    python3 tools/html_entities.py
"""
import hashlib
import json
import struct
import sys

SOURCE = "core/spell/entities/entities.json"
DIGEST = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"


def main():
    raw = open(SOURCE, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != DIGEST:
        sys.exit(f"{SOURCE}: sha256 {digest}, expected {DIGEST}")
    table = json.loads(raw)
    names = {}
    for key, entry in table.items():
        assert key[0] == "&" and all(ord(c) < 128 for c in key), key
        names[key[1:]] = entry["characters"].encode("utf-8")

    # A trie in breadth-first order, so that every node's children sit in a row.
    children = [{}]
    terminal = [None]
    for name, value in names.items():
        node = 0
        for c in name:
            nxt = children[node].get(c)
            if nxt is None:
                nxt = len(children)
                children[node][c] = nxt
                children.append({})
                terminal.append(None)
            node = nxt
        terminal[node] = value
    order = [0]
    first = {}
    for node in order:
        first[node] = len(order)
        for c in sorted(children[node]):
            order.append(children[node][c])
    char_of = {0: 0}
    for node in range(len(children)):
        for c, kid in children[node].items():
            char_of[kid] = ord(c)

    values = sorted(set(v for v in terminal if v is not None))
    value_index = {v: i for i, v in enumerate(values)}
    offsets, text = [], b""
    for v in values:
        offsets.append(len(text))
        text += v
    offsets.append(len(text))

    nodes, terminals = [], []
    for node in order:
        count = len(children[node])
        head = first[node] if count else 0
        assert char_of[node] < 128 and count < 64 and head < 1 << 19
        nodes.append(char_of[node] | count << 7 | head << 13)
        v = terminal[node]
        terminals.append(0 if v is None else 1 + value_index[v])
    assert len(values) < 1 << 16 and len(text) < 1 << 16

    open("core/spell/entities/nodes.bin", "wb").write(struct.pack(f"<{len(nodes)}I", *nodes))
    open("core/spell/entities/terminals.bin", "wb").write(struct.pack(f"<{len(terminals)}H", *terminals))
    open("core/spell/entities/offsets.bin", "wb").write(struct.pack(f"<{len(offsets)}H", *offsets))
    open("core/spell/entities/text.bin", "wb").write(text)
    with open("core/spell/entities.odin", "w") as out:
        out.write(f"""package spell

// Generated by tools/html_entities.py from core/spell/entities/entities.json (sha256 {DIGEST[:16]}...). Do not edit.
// The trie of the {len(names)} named character references of the HTML standard, {len(nodes)} nodes. Node 0 is the
// root. ENTITY_NODES[i] is `ch | count << 7 | first << 13`, ENTITY_TERMINALS[i] is 0 or 1 + a value index, and value
// v's UTF-8 bytes are ENTITY_TEXT[ENTITY_OFFSETS[v]:ENTITY_OFFSETS[v + 1]].

@(private, rodata)
ENTITY_NODES := #load("entities/nodes.bin", []u32)
@(private, rodata)
ENTITY_TERMINALS := #load("entities/terminals.bin", []u16)
@(private, rodata)
ENTITY_OFFSETS := #load("entities/offsets.bin", []u16)
@(private, rodata)
ENTITY_TEXT := #load("entities/text.bin")

// The child of trie node `node` for character `c`, or 0. Children are sorted by character.
entity_child :: #force_inline proc "contextless" (node: u32, c: u8) -> u32 #no_bounds_check {{
	w := ENTITY_NODES[node]
	lo := w >> 13
	hi := lo + (w >> 7) & 63
	for lo < hi {{
		mid := (lo + hi) >> 1
		ch := u8(ENTITY_NODES[mid] & 127)
		if ch == c {{
			return mid
		}}
		if ch < c {{
			lo = mid + 1
		}} else {{
			hi = mid
		}}
	}}
	return 0
}}

// The UTF-8 text of the reference whose name ends at trie node `node`, its `;` included when it has one, and false
// for a node no name ends at.
entity_value :: #force_inline proc "contextless" (node: u32) -> (text: []u8, ok: bool) #no_bounds_check {{
	v := ENTITY_TERMINALS[node]
	if v == 0 {{
		return nil, false
	}}
	return ENTITY_TEXT[ENTITY_OFFSETS[v - 1]:ENTITY_OFFSETS[v]], true
}}

// The UTF-8 text of the reference `name;`, the name written with its semicolon left off, and false for a name the
// standard does not list.
entity_named :: proc "contextless" (name: []u8) -> (text: []u8, ok: bool) {{
	node := u32(0)
	for c in name {{
		if c >= 0x80 {{
			return nil, false
		}}
		if node = entity_child(node, c); node == 0 {{
			return nil, false
		}}
	}}
	if node = entity_child(node, ';'); node == 0 {{
		return nil, false
	}}
	return entity_value(node)
}}
""")

main()
