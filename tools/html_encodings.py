#!/usr/bin/env python3
"""Write html/encodings.odin: the encodings of the Encoding Standard and the labels that name them, read from
html/encodings/encodings.json, the standard's own file, vendored with the digest below. The labels are sorted, so a
label is found by a binary search over its ASCII lowercase.

Run from the repository root:
    python3 tools/html_encodings.py
"""
import hashlib
import json
import sys

SOURCE = "html/encodings/encodings.json"
DIGEST = "078212b3697f60b81225b6671bd9da2604497abff0aa8e96e4d46605c02ac9e7"
OUT = "html/encodings.odin"


def ada(name):
    return "_".join(p[:1].upper() + p[1:].lower() for p in name.replace("-", "_").split("_"))


def main():
    raw = open(SOURCE, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != DIGEST:
        sys.exit(f"{SOURCE}: sha256 {digest}, expected {DIGEST}")
    names, labels = [], []
    for group in json.loads(raw):
        for e in group["encodings"]:
            names.append(e["name"])
            labels += [(label, e["name"]) for label in e["labels"]]
    labels.sort()
    assert len({ada(n) for n in names}) == len(names) and len({l for l, _ in labels}) == len(labels)
    assert all(l == l.lower() and l.isascii() for l, _ in labels)
    out = [
        "package html",
        "",
        f"// Generated by tools/html_encodings.py from {SOURCE} (sha256 {DIGEST[:16]}...). Do not edit.",
        f"// The {len(names)} encodings of the Encoding Standard, by the name it gives each, and its {len(labels)} labels, sorted.",
        "",
        "@(private)",
        "Encoding :: enum u8 {",
    ]
    out += [f"\t{ada(n)}," for n in names]
    out += ["}", "", "@(private, rodata)", "ENCODING_NAMES := [Encoding]string {"]
    out += [f'\t.{ada(n)} = "{n}",' for n in names]
    out += ["}", "", "@(private, rodata)", "ENCODING_LABELS := [?]struct {", "\tlabel:    string,",
            "\tencoding: Encoding,", "} {"]
    out += [f'\t{{"{l}", .{ada(n)}}},' for l, n in labels]
    out += ["}", ""]
    open(OUT, "w").write("\n".join(out))
    print(f"{OUT}: {len(names)} encodings, {len(labels)} labels")


if __name__ == "__main__":
    main()
