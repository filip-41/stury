#!/usr/bin/env python3
"""Write grammar_tables.odin: jq 1.8.2's LALR tables, as bison 3.8.2 built them into src/parser.c.

`parse` runs these tables the way bison's parser runs them, so a program parses, fails to, and recovers
from its errors exactly as it does in jq, with the same messages.

Run from the repository root, with parser.c from jq's sources at tag jq-1.8.2:
    python3 cmd/stury/jq/grammar_tables.py path/to/jq-1.8.2/src/parser.c
"""
import pathlib
import re
import sys

# Each terminal as bison names it, and the name `Sym` gives it, in bison's symbol order.
SYMBOLS = [
    ('"end of file"', "End"), ("error", "Error"), ('"invalid token"', "Undef"),
    ("INVALID_CHARACTER", "Invalid"), ("IDENT", "Ident"), ("FIELD", "Field"), ("BINDING", "Binding"),
    ("LITERAL", "Literal"), ("FORMAT", "Format"), ('".."', "Rec"), ('"%="', "Set_Mod"), ('"=="', "Eq"),
    ('"!="', "Neq"), ('"//"', "Alt"), ('"as"', "As"), ('"def"', "Def"), ('"module"', "Module"),
    ('"import"', "Import"), ('"include"', "Include"), ('"if"', "If"), ('"then"', "Then"), ('"else"', "Else"),
    ('"elif"', "Elif"), ('"reduce"', "Reduce"), ('"foreach"', "Foreach"), ('"end"', "End_Kw"), ('"and"', "And"),
    ('"or"', "Or"), ('"try"', "Try"), ('"catch"', "Catch"), ('"label"', "Label"), ('"break"', "Break"),
    ('"$__loc__"', "Loc"), ('"|="', "Set_Pipe"), ('"+="', "Set_Plus"), ('"-="', "Set_Minus"),
    ('"*="', "Set_Mult"), ('"/="', "Set_Div"), ('"//="', "Set_Alt"), ('"<="', "Less_Eq"), ('">="', "Greater_Eq"),
    ('"?//"', "Alternation"), ("QQSTRING_START", "QQ_Start"), ("QQSTRING_TEXT", "QQ_Text"),
    ("QQSTRING_INTERP_START", "QQ_Interp_Start"), ("QQSTRING_INTERP_END", "QQ_Interp_End"),
    ("QQSTRING_END", "QQ_End"), ("FUNCDEF", "Funcdef"), ("'|'", "Pipe"), ("','", "Comma"), ("'='", "Assign"),
    ("'<'", "Less"), ("'>'", "Greater"), ("'+'", "Plus"), ("'-'", "Minus"), ("'*'", "Star"), ("'/'", "Slash"),
    ("'%'", "Percent"), ("NONOPT", "Nonopt"), ("'?'", "Question"), ("'.'", "Dot"), ("'['", "LBracket"),
    ("';'", "Semi"), ("':'", "Colon"), ("'('", "LParen"), ("')'", "RParen"), ("']'", "RBracket"),
    ("'{'", "LBrace"), ("'}'", "RBrace"), ("'$'", "Dollar"),
]

TABLES = [  # bison's name, ours, element type
    ("yypact", "PACT", "i16"), ("yydefact", "DEFACT", "u8"), ("yypgoto", "PGOTO", "i16"),
    ("yydefgoto", "DEFGOTO", "u16"), ("yytable", "TABLE", "i16"), ("yycheck", "CHECK", "i16"),
    ("yyr1", "RULE_LHS", "i8"), ("yyr2", "RULE_LEN", "u8"),
]


def table(src, name):
    m = re.search(r"static const \w+ %s\[\] =\s*\{(.*?)\};" % name, src, re.S)
    return [int(x) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]


def define(src, name):
    return int(re.search(r"#define %s\s+\(?(-?\d+)\)?" % name, src).group(1))


def tname(src):
    """yytname's terminals, each as bison's messages show it (yytnamerr: a quoted name loses its quotes)."""
    body = re.search(r"yytname\[\] =\s*\{(.*?)YY_NULLPTR", src, re.S).group(1)
    return [bytes(s, "ascii").decode("unicode_escape") for s in re.findall(r'"((?:[^"\\]|\\.)*)"', body)]


def shown(name):
    if name.startswith('"') and not re.search(r"['\\,]", name[1:-1]):
        return name[1:-1]
    return name


def rows(values, per=16):
    return ["\t" + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per)]


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    assert "Bison 3.8.2" in src
    names = tname(src)
    ntokens = define(src, "YYNTOKENS")
    assert [n for n, _ in SYMBOLS] == names[:ntokens], "jq's terminals are not those SYMBOLS lists"
    out = [
        "package jq",
        "",
        "// Generated by grammar_tables.py from jq 1.8.2's src/parser.c (bison 3.8.2); do not edit. The",
        "// tables are bison's: PACT, DEFACT, PGOTO, DEFGOTO, TABLE and CHECK drive the LALR parser, RULE_LHS",
        "// and RULE_LEN describe each rule, numbered as in jq's parser.y.",
        "// jq is MIT licensed, copyright (C) 2012 Stephen Dolan: see cmd/stury/jq-1.8.2/COPYING.",
        "",
        "FINAL :: %d" % define(src, "YYFINAL"),
        "LAST :: %d" % define(src, "YYLAST"),
        "NTOKENS :: %d" % ntokens,
        "PACT_NINF :: %d" % define(src, "YYPACT_NINF"),
        "TABLE_NINF :: %d" % define(src, "YYTABLE_NINF"),
        "",
        "// The terminals, in bison's order.",
        "Sym :: enum u8 {",
    ] + ["\t%s," % odin for _, odin in SYMBOLS] + [
        "}",
        "",
        "// Each terminal as a syntax error names it.",
        "@(rodata)",
        "SYM_NAMES: [NTOKENS]string = {",
    ] + ['\t"%s",' % shown(n).replace("\\", "\\\\").replace('"', '\\"') for n in names[:ntokens]] + ["}"]
    for bison, ours, typ in TABLES:
        values = table(src, bison)
        if bison == "yyr1":
            values = [v - ntokens for v in values]
        out += ["", "@(rodata)", "%s: [%d]%s = {" % (ours, len(values), typ)] + rows(values) + ["}"]
    path = pathlib.Path(__file__).with_name("grammar_tables.odin")
    path.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
