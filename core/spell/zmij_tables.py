#!/usr/bin/env python3
"""Write zmij_tables.odin: the powers of ten `to_decimal` scales by.

POW10_SIG[k + 342] is the 128-bit significand of 10^k, truncated toward zero with bit 127 set, for
-342 <= k <= 341. It is computed exactly with Python integers; `to_decimal` needs the floor, which is what
`exact_pow10` returns.

Run from the repository root: python3 core/spell/zmij_tables.py
"""

import pathlib

MASK = (1 << 64) - 1
MIN_EXP = -342
MAX_EXP = 341


def exact_pow10(k):
    """The 128-bit floor of 10^k, normalized so bit 127 is set."""
    if k >= 0:
        v = 10 ** k
        n = v.bit_length()
        return v << (128 - n) if n <= 128 else v >> (n - 128)
    d = 10 ** -k
    # The smallest s with 2^s / d >= 2^127; floor(2^s / d) then has exactly 128 bits.
    s = 127 + d.bit_length()
    q = (1 << s) // d
    assert q.bit_length() == 128
    return q


rows = []
for k in range(MIN_EXP, MAX_EXP + 1):
    v = exact_pow10(k)
    rows.append((v >> 64, v & MASK))
assert all(hi >> 63 for hi, _ in rows)
assert rows[-MIN_EXP] == (0x8000000000000000, 0)
assert rows[0] == (0xeef453d6923bd65a, 0x113faa2906a13b3f)
assert rows[-1] == (0xdb68c2ca82ed2a05, 0xa67398db9f6820e1)

out = pathlib.Path(__file__).resolve().with_suffix(".odin")
with out.open("w") as f:
    f.write("package spell\n\n")
    f.write("// Generated by zmij_tables.py; do not edit.\n")
    f.write("//\n")
    f.write("// `POW10_SIG[k + 342]` is the 128-bit significand of 10^k, truncated toward zero with bit 127 set, for\n")
    f.write("// -342 <= k <= 341. Each row is (high, low); both `to_decimal` functions scale by it.\n")
    f.write("@(private, rodata)\n")
    f.write("POW10_SIG: [%d][2]u64 = {\n" % len(rows))
    for i, (hi, lo) in enumerate(rows):
        f.write("\t{0x%016x, 0x%016x}, // 10^%d\n" % (hi, lo, MIN_EXP + i))
    f.write("}\n")
